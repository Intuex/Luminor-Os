extern "C" void putchar(char c)
{
    if (!fb) return;

    if (c == '\n') {
        cursor_x = 0;
        cursor_y++;
        return;
    }

    if (c == '\b') {
        if (cursor_x > 0) cursor_x--;
        int px = cursor_x * CHAR_W;
        int py = cursor_y * CHAR_H;
        for (int row = 0; row < CHAR_H; row++)
            for (int col = 0; col < CHAR_W; col++)
                fb[(py + row) * (fb_pitch / 4) + (px + col)] = 0x000000;
        return;
    }

    if (c < 32 || c > 127) return;

    const uint8_t* glyph = font[c - 32];
    int px = cursor_x * CHAR_W;
    int py = cursor_y * CHAR_H;

    for (int row = 0; row < CHAR_H; row++)
        for (int col = 0; col < CHAR_W; col++)
            fb[(py + row) * (fb_pitch / 4) + (px + col)] =
                (glyph[row] & (1 << (7 - col))) ? 0xFFFFFF : 0x000000;

    cursor_x++;
    if ((uint64_t)(cursor_x * CHAR_W) >= fb_width) {
        cursor_x = 0;
        cursor_y++;
    }
}

extern "C" void print(const char* s)
{
    for (int i = 0; s[i]; i++)
        putchar(s[i]);
}

extern "C" void clear_screen()
{
    if (!fb) return;
    for (uint64_t y = 0; y < fb_height; y++)
        for (uint64_t x = 0; x < fb_width; x++)
            fb[y * (fb_pitch / 4) + x] = 0x000000;
    cursor_x = 0;
    cursor_y = 0;
}

extern "C" int strncmp(const char* a, const char* b, int n)
{
    for (int i = 0; i < n; i++)
        if (a[i] != b[i])
            return 1;
    return 0;
}

extern "C" void run_command(char* cmd)
{
    if (!strncmp(cmd, "print(\"", 7))
    {
        char* text = cmd + 7;
        while (*text && *text != '"') {
            putchar(*text);
            text++;
        }
        putchar('\n');
        return;
    }

    if (!strncmp(cmd, "clear", 5))
    {
        clear_screen();
        return;
    }

    print("Unknown command\n");
}

extern "C" void _start()
{
    if (fb_request.response && fb_request.response->count > 0) {
        limine_framebuffer* f = fb_request.response->framebuffers[0];
        fb        = (uint32_t*)f->address;
        fb_width  = f->width;
        fb_height = f->height;
        fb_pitch  = f->pitch;
    }

    clear_screen();
    print("Luminor OS\n");
    print("> ");

    while (1)
    {
        char c = keyboard_getchar();
        if (!c) continue;

        if (c == '\n')
        {
            putchar('\n');
            input[input_pos] = 0;
            run_command(input);
            input_pos = 0;
            print("> ");
        }
        else if (c == '\b')
        {
            if (input_pos > 0)
            {
                input_pos--;
                putchar('\b');
            }
        }
        else
        {
            if (input_pos < (int)sizeof(input) - 1)
            {
                input[input_pos++] = c;
                putchar(c);
            }
        }
    }
}